def s5_moves():
    """(old, new) for every tracked path Stage 5 renames."""
    out = []
    for p in tracked():
        n = p
        for a, b in S5_DIRS:
            if n == a or n.startswith(a + "/"):
                n = b + n[len(a):]
        if n.startswith(("ios/", ".github/")):
            d, base = os.path.split(n)
            for rx, rep in S5_FILE:
                base = rx.sub(rep, base, count=1)
            n = os.path.join(d, base)
        if n != p:
            out.append((p, n))
    return out


