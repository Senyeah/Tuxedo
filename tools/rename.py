COMMENT = re.compile(r"^\s*(//|#|\*|/\*|--|;)")
CODE_EXT = (".swift", ".c", ".h", ".m", ".py", ".sh", ".S", ".js")


def md_prose_line(line, state):
    if line.lstrip().startswith("```"):
        state["fence"] = not state["fence"]
        return False
    return not state["fence"]


def run_stage(n, apply):
    st, keep, m = STAGES[n], Keep(), load_map()
    changed = Counter()
    if st.get("moves"):
        mv = s5_moves()
        for a, b in mv:
            print(f"mv  {a} -> {b}")
            if apply:
                os.makedirs(os.path.dirname(os.path.join(ROOT, b)), exist_ok=True)
                subprocess.check_call(["git", "mv", a, b], cwd=ROOT)
        print(f"{len(mv)} paths moved" if apply else f"{len(mv)} paths would move")
    for p in tracked():
        if keep.path(p) or not any(fnmatch.fnmatch(p, g) for g in st["globs"]) or any(fnmatch.fnmatch(p, g) for g in st["skip"]):
            continue
        t = read(p)
        if t is None:
            continue
        rules = list(st.get("rules", [])) + [r for g, rs in st.get("file_rules", []) if fnmatch.fnmatch(p, g) for r in rs]
        out, fence = [], {"fence": False}
        for i, line in enumerate(t.split("\n"), 1):
            new = line
            ok = not keep.line(p, i, line)
            if ok and p.endswith(".md") and st.get("md_prose"):
                ok = md_prose_line(line, fence)
            elif ok and st.get("code_comments"):
                ok = p.endswith(CODE_EXT) or p == "Makefile"
                ok = ok and bool(COMMENT.match(line)) and not line.startswith("#!")
            if ok:
                def sub(mm):
                    tok = mm.group(0)
                    if not st["token"](tok):
                        return tok
                    if st.get("ctx") and not st["ctx"](p, line, mm.start(), mm.end(), tok):
                        return tok
                    if tok not in m:
                        sys.exit(f"{p}:{i}: token {tok} is not in the map")
                    return m[tok]
                if st.get("md_prose") and p.endswith(".md"):
                    # Skip inline code spans.
                    parts = re.split(r"(`[^`]*`)", line)
                    new = "".join(x if x.startswith("`") else TOKEN.sub(sub, x) for x in parts)
                else:
                    new = TOKEN.sub(sub, line)
            if ok:
                for rx, rep in rules:
                    new = rx.sub(rep, new)
            for g, a, b in st.get("literals", []):
                if fnmatch.fnmatch(p, g) and not keep.line(p, i, line):
                    new = new.replace(a, b)
            if new != line:
                changed[p] += 1
            out.append(new)
        if apply and p in changed:
            with open(os.path.join(ROOT, p), "w") as f:
                f.write("\n".join(out))
    for p, c in sorted(changed.items()):
        print(f"{c:5d}  {p}")
    print(f"stage {n}: {sum(changed.values())} lines in {len(changed)} files ({'applied' if apply else 'dry run'})")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--gen-map", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--stage", type=int)
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()
    if a.gen_map: gen_map()
    elif a.check: check()
    elif a.stage:
        if a.stage not in STAGES:
            sys.exit(f"stage {a.stage} has no allow-list yet (add it when that stage starts)")
        run_stage(a.stage, a.apply)
    else: ap.print_help()
