def stage4_ctx(path, line, s, e, tok):
    """False to leave this one occurrence alone."""
    if S4_KEEP_LINE.search(line):
        return False
    if tok == "hengevm" and line[e:e + 5] == "-disk":
        return False  # hengevm-disk: Stage 6
