"""Henge to Tuxedo rename (docs/rename-tuxedo-plan.md, Stage 0).

  rename.py --gen-map              write tools/rename-map.txt from the tree
  rename.py --check                fail if a henge token is not in the map
  rename.py --stage N [--apply]    show (or make) the changes of stage N
"""
import argparse, fnmatch, os, re, subprocess, sys
from collections import Counter

ROOT = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
TOOLS = os.path.join(ROOT, "tools")
MAP_FILE = os.path.join(TOOLS, "rename-map.txt")
KEEP_FILE = os.path.join(TOOLS, "rename-keep.txt")

TOKEN = re.compile(r"[A-Za-z0-9_]*[Hh][Ee][Nn][Gg][Ee][A-Za-z0-9_]*")
# Phrases that map as a whole, before the token rules.
PHRASES = [
    ("nz.jackgreenhill.henge", "nz.jackgreenhill.tuxedo"),
    ("com.henge.linux-wallet", "nz.jackgreenhill.tuxedo.linux-wallet"),
    ("com.henge.agent", "nz.jackgreenhill.tuxedo.agent"),
    ("com.henge.app", "nz.jackgreenhill.tuxedo"),
    ("dev.henge.Keyboard", "nz.jackgreenhill.tuxedo.Keyboard"),
]


def map_token(tok):
    if tok == "Henge":
        return "Tuxedo"
    if "Henge" in tok and tok.replace("Henge", "") == "":
        return "Tux"
    return tok.replace("Henge", "Tux").replace("HENGE", "TUX").replace("henge", "tux")


def tracked():
    out = subprocess.check_output(["git", "ls-files", "-z"], cwd=ROOT).split(b"\0")
    return [p.decode() for p in out if p]


def read(path):
    try:
        with open(os.path.join(ROOT, path), "rb") as f:
            b = f.read()
    except OSError:
        return None
    if b"\0" in b[:8192]:
        return None
    try:
        return b.decode()
    except UnicodeDecodeError:
        return None


class Keep:
    """tools/rename-keep.txt: path:<glob>, line-re:<regex>, lines:<path>:<a>-<b>."""

    def __init__(self):
        self.paths, self.line_res, self.ranges = [], [], []
        for raw in open(KEEP_FILE):
            s = raw.rstrip("\n")
            if not s or s.startswith("#"):
                continue
            kind, _, rest = s.partition(":")
            if kind == "path":
                self.paths.append(rest)
            elif kind == "line-re":
                self.line_res.append(re.compile(rest))
            elif kind == "lines":
                p, _, r = rest.rpartition(":")
                a, _, b = r.partition("-")
                self.ranges.append((p, int(a), int(b or a)))

    def path(self, p):
        return any(fnmatch.fnmatch(p, g) for g in self.paths)

    def line(self, p, n, text):
        return any(a <= n <= b for q, a, b in self.ranges if q == p) or any(r.search(text) for r in self.line_res)


def swap_line(line):
    for old, new in PHRASES:
        line = line.replace(old, new)
    return TOKEN.sub(lambda m: map_token(m.group(0)), line)


def distinct_tokens(keep):
    seen = Counter()
    for p in tracked():
        if keep.path(p):
            continue
        t = read(p)
        if t is None:
            continue
        for n, line in enumerate(t.split("\n"), 1):
            if keep.line(p, n, line):
                continue
            for old, _ in PHRASES:
                line = line.replace(old, " ")
            for m in TOKEN.finditer(line):
                seen[m.group(0)] += 1
    return seen


def load_map():
    m = {}
    for raw in open(MAP_FILE):
        if raw.startswith("#") or not raw.strip():
            continue
        a, _, b = raw.rstrip("\n").partition("\t")
        m[a] = b
    return m


def gen_map():
    seen = distinct_tokens(Keep())
    with open(MAP_FILE, "w") as f:
        f.write("# old<TAB>new, one distinct henge token per line. Generated by tools/rename.py --gen-map.\n")
        f.write("# Edit a line to override the rule. Whole phrases (PHRASES in rename.py) map before tokens.\n")
        for old, new in PHRASES:
            f.write(f"# phrase: {old} -> {new}\n")
        for tok, n in sorted(seen.items(), key=lambda kv: kv[0].lower()):
            f.write(f"{tok}\t{map_token(tok)}\n")
    print(f"{len(seen)} tokens written to {os.path.relpath(MAP_FILE, ROOT)}")


def check():
    keep, m = Keep(), load_map()
    bad = [t for t in distinct_tokens(keep) if t not in m]
    for t in bad:
        print("not in map:", t)
    # A mixed-case spelling the rules do not know is a bug in the tree or the rules.
    odd = [t for t in m if not re.search(r"Henge|HENGE|henge", t)]
    for t in odd:
        print("odd case:", t)
    sys.exit(1 if bad or odd else 0)


# Stages: path globs to touch, globs to skip, and a token test.
def is_ident_caps(t): return "HENGE" in t
def is_engine_ident(t):
    return bool(re.search(r"^(henge_vm_|henge_ios_jit_|henge_args|hengevm|libhenge(vm|restore)|epoxy_henge)|HENGE_|^Henge[A-Z]|^henge[A-Z]", t)) \
        or t in ("hengevm", "hengerestore")

STAGES = {
    3: dict(globs=["*.md"], skip=["docs/rename-tuxedo-plan.md", "CHANGELOG.md"],
            token=lambda t: t == "Henge", md_prose=True),
    4: dict(globs=["ios/*", "host/*", "core/*", "devices/*", "tests/*", "tools/*", "third_party/*", "Makefile", "*.sh"],
            skip=["tools/linux/henge-guest/*", "tools/linux/henge-va/*", "tools/linux/henge-ffmpeg/*",
                  "tools/linux/henge-codec-dkms/*", "tools/linux/rootfs*", "tools/linux/customize.sh",
                  "tools/rename*", "*.md", "ios/TrackpadLab/*", "tools/linux/hvcodec/ffmpeg-henge.patch"],
            token=is_engine_ident, no_phrases=True),
}


def md_prose_line(line, state):
    if line.lstrip().startswith("```"):
        state["fence"] = not state["fence"]
        return False
    return not state["fence"]


def run_stage(n, apply):
    st, keep, m = STAGES[n], Keep(), load_map()
    changed = Counter()
    for p in tracked():
        if keep.path(p) or not any(fnmatch.fnmatch(p, g) for g in st["globs"]) or any(fnmatch.fnmatch(p, g) for g in st["skip"]):
            continue
        t = read(p)
        if t is None:
            continue
        out, fence = [], {"fence": False}
        for i, line in enumerate(t.split("\n"), 1):
            new = line
            ok = not keep.line(p, i, line)
            if ok and st.get("md_prose"):
                ok = md_prose_line(line, fence)
            if ok:
                def sub(mm):
                    tok = mm.group(0)
                    if not st["token"](tok):
                        return tok
                    if tok not in m:
                        sys.exit(f"{p}:{i}: token {tok} is not in the map")
                    return m[tok]
                if st.get("md_prose"):
                    # Skip inline code spans.
                    parts = re.split(r"(`[^`]*`)", line)
                    new = "".join(x if x.startswith("`") else TOKEN.sub(sub, x) for x in parts)
                else:
                    new = TOKEN.sub(sub, line)
            if new != line:
                changed[p] += 1
            out.append(new)
        if apply and p in changed:
            with open(os.path.join(ROOT, p), "w") as f:
                f.write("\n".join(out))
    for p, c in sorted(changed.items()):
        print(f"{c:5d}  {p}")
    print(f"stage {n}: {sum(changed.values())} lines in {len(changed)} files ({'applied' if apply else 'dry run'})")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--gen-map", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--stage", type=int)
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()
    if a.gen_map: gen_map()
    elif a.check: check()
    elif a.stage:
        if a.stage not in STAGES:
            sys.exit(f"stage {a.stage} has no allow-list yet (add it when that stage starts)")
        run_stage(a.stage, a.apply)
    else: ap.print_help()
